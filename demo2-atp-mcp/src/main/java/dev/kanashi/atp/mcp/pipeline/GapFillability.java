package dev.kanashi.atp.mcp.pipeline;

/**
 * 一个缺失字段<b>应该由谁来补</b>。
 *
 * <h2>为什么这个区分是本 demo 最重要的判断之一</h2>
 * "让模型少做事"通常被理解成"能用规则做的别给模型"。但还有更关键的一半：
 * <b>有些字段模型根本没有信息来源，让它补就是让它编。</b>
 * <p>
 * 最典型的是 {@code locator_value} —— 模型<b>从未见过被测页面</b>。
 * 让它补一个 XPath，它一定能写出一个语法正确、看起来很合理的表达式，
 * 而这个表达式指向的元素<b>可能根本不存在</b>。schema 校验会通过（是字符串），
 * 规范检查也可能通过（用了 data-testid），一路绿灯进库，
 * 直到执行器报"元素未找到"——那时没人会想到根因是几天前模型编了个选择器。
 * <p>
 * 同理 {@code author}（编一个人名）与 {@code expected}（它不知道正确结果是什么）。
 * <p>
 * 所以缺口分析不只回答"缺了什么"，还要回答"这个缺口该找谁"。
 * 找错人比不找更糟。
 */
public enum GapFillability {

    /**
     * 模型可以基于案例已有内容合理推断。
     * <p>
     * 判据是<b>答案能否从上下文中推出</b>：module_id 能从标题和步骤语义匹配到字典项，
     * priority 能从业务重要性推断，locator_type 能从 locator_value 的写法判断。
     * 这些都是"信息已经在案例里，只是需要理解"。
     */
    MODEL,

    /**
     * 只能由请求方提供，<b>模型补即为编造</b>。
     * <p>
     * 命中即 REJECTED —— 宁可拒绝，不可错入。
     */
    REQUESTER,

    /**
     * 由平台在入库时分配（如 case_code 的全局唯一序号）。
     * <p>
     * 本服务无状态，给不了；但这不构成拒绝理由，标注清楚交给平台即可。
     */
    PLATFORM
}
